from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "design" / "registry" / "experience_registry_v1.json"
MARKDOWN = ROOT / "design" / "registry" / "EXPERIENCE_STATUS.md"
HTML = ROOT / "design" / "manager" / "index.html"

STATUSES = {"FROZEN","ACTIVE_CLOSURE","PARTIAL","RUNTIME_ONLY","DESIGN_ONLY","MISSING","DEPRECATED"}
MODS = ["behavior","visual","motion","haptic","sound","runtime","evidence"]
ICON = {"FROZEN":"✅","ACTIVE_CLOSURE":"🟡","PARTIAL":"🟠","RUNTIME_ONLY":"🔵","DESIGN_ONLY":"🟣","MISSING":"❌","DEPRECATED":"⚫"}


def load():
    try:
        data = json.loads(REGISTRY.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"cannot read registry: {exc}") from exc
    if not isinstance(data, dict):
        raise ValueError("registry root must be an object")
    return data


def validate(data):
    errors = []
    if set(data.get("status_vocabulary", [])) != STATUSES:
        errors.append("status_vocabulary does not match governance vocabulary")
    features = data.get("features")
    if not isinstance(features, list):
        return errors + ["features must be a list"]

    seen = set()
    for i, feature in enumerate(features):
        if not isinstance(feature, dict):
            errors.append(f"features[{i}] must be an object")
            continue
        fid = feature.get("id")
        if not isinstance(fid, str) or not fid:
            errors.append(f"features[{i}].id is invalid")
            continue
        if fid in seen:
            errors.append(f"duplicate feature id: {fid}")
        seen.add(fid)
        if feature.get("overall") not in STATUSES:
            errors.append(f"{fid}: invalid overall status")
        if not isinstance(feature.get("owner_path"), str):
            errors.append(f"{fid}: owner_path is invalid")
        modalities = feature.get("modalities")
        if not isinstance(modalities, dict):
            errors.append(f"{fid}: modalities must be an object")
            continue
        for mod in MODS:
            entry = modalities.get(mod)
            if not isinstance(entry, dict):
                errors.append(f"{fid}: missing modality {mod}")
                continue
            status = entry.get("status")
            if status not in STATUSES:
                errors.append(f"{fid}/{mod}: invalid status {status!r}")
            authority = entry.get("authority")
            if authority is None:
                if status == "FROZEN":
                    errors.append(f"{fid}/{mod}: FROZEN requires authority")
            elif not isinstance(authority, str) or not authority:
                errors.append(f"{fid}/{mod}: invalid authority")
            elif not (ROOT / authority).exists():
                errors.append(f"{fid}/{mod}: authority does not exist: {authority}")
    return errors


def markdown(data):
    features = data["features"]
    counts = Counter(f["overall"] for f in features)
    lines = [
        "# YuJian Experience Status",
        "",
        "> AUTO-GENERATED by scripts/experience_manager.py build.",
        "> Update experience_registry_v1.json and feature contracts instead of editing this file.",
        "",
        f"Registry version: **{data.get('version','unknown')}**  ",
        f"Features: **{len(features)}**  ",
        "Overall: " + " · ".join(f"{ICON.get(k,'')} {k} {v}" for k,v in sorted(counts.items())),
        "",
        "## Feature matrix",
        "",
        "| Feature | Overall | Behavior | Visual | Motion | Haptic | Sound | Runtime | Evidence |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for f in features:
        row = [f["id"], f"{ICON.get(f['overall'],'')} {f['overall']}"]
        for mod in MODS:
            s = f["modalities"][mod]["status"]
            row.append(f"{ICON.get(s,'')} {s}")
        lines.append("| " + " | ".join(row) + " |")

    lines += ["", "## Gaps / active closure", ""]
    found = False
    for f in features:
        items = []
        for mod in MODS:
            s = f["modalities"][mod]["status"]
            if s != "FROZEN":
                items.append(f"{mod}={s}")
        if items or f["overall"] != "FROZEN":
            found = True
            lines.append(f"- **{f['id']}** — overall {f['overall']}; " + ", ".join(items))
    if not found:
        lines.append("- None.")
    lines += ["", "## Commands", "", "    python3 scripts/experience_manager.py validate", "    python3 scripts/experience_manager.py summary", "    python3 scripts/experience_manager.py build", ""]
    return "\n".join(lines)


