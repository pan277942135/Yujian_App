def build(data):
    MARKDOWN.parent.mkdir(parents=True, exist_ok=True)
    HTML.parent.mkdir(parents=True, exist_ok=True)
    MARKDOWN.write_text(markdown(data), encoding="utf-8")
    HTML.write_text(dashboard(data), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description="YuJian Experience Manager")
    parser.add_argument("command", choices=["validate","summary","build"])
    args = parser.parse_args()
    try:
        data = load()
    except ValueError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1
    errors = validate(data)
    if errors:
        for error in errors:
            print("ERROR " + error, file=sys.stderr)
        print(f"FAIL: {len(errors)} registry issue(s)", file=sys.stderr)
        return 1
    if args.command == "validate":
        print(f"PASS: registry valid; {len(data['features'])} features")
    elif args.command == "summary":
        print(markdown(data))
    else:
        build(data)
        print("PASS: generated experience status and dashboard")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
